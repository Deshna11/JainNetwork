/**
 * Returns a list of locations combining verified Indian locations with any additional cities from the DB.
 */
export function getMergedLocations(dbCities: string[] = []): LocationItem[] {
  const map = new Map<string, string>();

  // Add default predefined locations
  for (const loc of INDIA_LOCATIONS) {
    map.set(loc.city.toLowerCase(), loc.state);
  }

  // Add DB cities if not already mapped
  for (const dbCity of dbCities) {
    if (dbCity && !map.has(dbCity.toLowerCase())) {
      map.set(dbCity, 'India');
    }
  }

  // Convert back to LocationItem array sorted by city name
  const result: LocationItem[] = Array.from(map.entries()).map(([cityKey, state]) => {
    // Find original case if present
    const original = INDIA_LOCATIONS.find((l) => l.city.toLowerCase() === cityKey);
    return {
      city: original ? original.city : cityKey,
      state: state,
    };
  });

  return result.sort((a, b) => a.city.localeCompare(b.city));
}
